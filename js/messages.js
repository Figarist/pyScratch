  function currentLang() {
    const i18n = global.PyScratchI18n;
    const lang = i18n && typeof i18n.getLang === 'function' ? i18n.getLang() : null;
    return lang && MESSAGES[lang] ? lang : 'uk';
  }

  // Single-pass substitution, so a value that itself contains "{name}" is never expanded again.
  function format(key, params, lang) {
    const table = MESSAGES[lang || currentLang()] || MESSAGES.uk;
    const template = table[key] != null ? table[key] : MESSAGES.uk[key] != null ? MESSAGES.uk[key] : key;
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (m, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m
    );
  }

  const api = { MESSAGES, format, currentLang };
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = api;
  } else {
    global.PyScratchMessages = api;
  }
